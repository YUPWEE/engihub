"""Local PDF storage under random filenames, with a total quota from STORAGE_QUOTA_MB."""

import asyncio
import os
import secrets
from pathlib import Path

UPLOAD_DIR = Path(os.environ.get("UPLOAD_DIR", str(Path(__file__).parent.parent / "uploads")))
MAX_PDF_BYTES = 15 * 1024 * 1024


def quota_bytes() -> int:
    return int(float(os.environ.get("STORAGE_QUOTA_MB", "2048")) * 1024 * 1024)


def _used() -> int:
    if not UPLOAD_DIR.exists():
        return 0
    return sum(f.stat().st_size for f in UPLOAD_DIR.iterdir() if f.is_file())


async def used_bytes() -> int:
    return await asyncio.to_thread(_used)


def path_for(name: str) -> Path:
    # names are generated by us (hex + .pdf); guard against traversal anyway
    return UPLOAD_DIR / Path(name).name


def _write(data: bytes) -> str:
    UPLOAD_DIR.mkdir(parents=True, exist_ok=True)
    name = secrets.token_hex(16) + ".pdf"
    path_for(name).write_bytes(data)
    return name


async def save_pdf(data: bytes) -> str:
    return await asyncio.to_thread(_write, data)


async def delete_file(name: str | None) -> None:
    if not name:
        return
    p = path_for(name)
    await asyncio.to_thread(lambda: p.unlink(missing_ok=True))
