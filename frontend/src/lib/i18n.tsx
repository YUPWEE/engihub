export type Lang = "ar" | "en";
const DICTS: Record<Lang, Record<TKey, string>> = { ar, en };
const STORAGE_KEY = "engihub_lang";

// English singular forms for count strings ("1 course", not "1 courses"). Arabic phrases here are number-neutral.
const EN_SINGULAR = { coursesCount: "{n} course", resourcesCount: "{n} resource" } as const;

interface I18n {
  lang: Lang;
  dir: "rtl" | "ltr";
  setLang: (l: Lang) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
}

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    return localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "ar";
  } catch {
    return "ar";
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const dir = lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    document.title =
      lang === "ar"
        ? "EngiHub — مصادر مقررات كلية الهندسة | جامعة الملك سعود"
        : "EngiHub — Course resources for KSU College of Engineering";
  }, [lang, dir]);

  const value = useMemo<I18n>(
    () => ({
      lang,
      dir,
      setLang: (l) => {
        try {
          localStorage.setItem(STORAGE_KEY, l);
        } catch {
          /* private mode — keep in memory only */
        }
        setLangState(l);
      },
      t: (key, vars) => {
        let s = DICTS[lang][key] ?? key;
        if (lang === "en" && vars?.n === 1 && key in EN_SINGULAR) s = EN_SINGULAR[key as keyof typeof EN_SINGULAR];
        if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
        return s;
      },
    }),
    [lang, dir],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n outside I18nProvider");
  return v;
}

export function isTKey(k: string): k is TKey {
  return k in en;
}
